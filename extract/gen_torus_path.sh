# Build the MAlonzo extractor from agda/ExtractTorusPath.agda (which imports
# the checked agda/TorusInvariant.agda) and emit extract/torus_path.h.
# Usage: extract/gen_torus_path.sh [N]   (default N = 4096, rows t = 0..N-1)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
N="${1:-4096}"
case "$N" in (''|*[!0-9]*) echo "N must be a decimal natural number" >&2; exit 2;; esac
# uint64 range: 2462 * (N-1) must be < 2^64.
if [ "${#N}" -gt 15 ]; then echo "N too large for uint64 rows" >&2; exit 2; fi
cd "$ROOT/agda"
agda --compile --compile-dir="$ROOT/_build/malonzo" ExtractTorusPath.agda >&2
BIN="$ROOT/_build/malonzo/ExtractTorusPath"
SRC_SHA=$(sha256sum TorusInvariant.agda | cut -d' ' -f1)
DRV_SHA=$(sha256sum ExtractTorusPath.agda | cut -d' ' -f1)
AGDA_VER=$(agda --version | head -1)
GHC_VER=$(ghc --numeric-version)
OUT="$ROOT/extract/torus_path.h"
TMP="$OUT.tmp.$$"
{
  echo "/* SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-SnapKitty-Opaque-1.0"
  echo " * Copyright (C) 2026 Ahmad Ali Parr / SnapKitty Research Lab"
  echo " *"
  echo " * GENERATED by extract/gen_torus_path.sh. Do not edit by hand."
  echo " * Verified 89/2462 knot path: rows (m, l) = (89*t, 2462*t)."
  echo " * Each row is proj1 of TorusInvariant.collapseToVerified t, whose type"
  echo " * VerifiedState = Sigma KnotCoord Invariant carries 2462*m == 89*l."
  echo " * Resolution: integer step t, unwrapped (no modular phase wrapping)."
  echo " * t-range: 0 .. $((N - 1)) inclusive ($N rows)."
  echo " * Source: agda/TorusInvariant.agda sha256 $SRC_SHA"
  echo " * Driver: agda/ExtractTorusPath.agda sha256 $DRV_SHA"
  echo " * Checker: $AGDA_VER (MAlonzo backend, GHC $GHC_VER)"
  echo " */"
  echo "#ifndef SPME_TORUS_PATH_H"
  echo "#define SPME_TORUS_PATH_H"
  echo "#include <stdint.h>"
  echo "typedef struct { uint64_t m; uint64_t l; } spme_knot_coord_t;"
  echo "#define SPME_TORUS_MERIDIAN 89u"
  echo "#define SPME_TORUS_LONGITUDE 2462u"
  echo "#define SPME_TORUS_T_MIN 0u"
  echo "#define SPME_TORUS_T_MAX $((N - 1))u"
  "$BIN" "$N"
  echo "#endif /* SPME_TORUS_PATH_H */"
} > "$TMP"
mv "$TMP" "$OUT"
echo "wrote $OUT ($N rows)" >&2
